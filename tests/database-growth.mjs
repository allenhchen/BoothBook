import assert from 'node:assert/strict';
import { createTestDatabase, loadTypeScript } from './helpers/runtime.mjs';
const store = loadTypeScript('lib/artist-store.ts');
let reads = [], writes = [];
const { sqlite, db } = createTestDatabase({ onRead: sql => reads.push(sql), onWrite: sql => writes.push(sql) });
const artist = { id: 'chatgpt:growth', email: 'growth@example.test', displayName: 'Growth', provider: 'chatgpt' };
const sales = Array.from({ length: 5000 }, (_, n) => ({ id: 'sale-' + n, eventId: n % 2 ? 'a' : 'b', date: '2026-10-06T10:00:00Z', reference: '', lines: [{ itemId: 'i', name: '=1+1 ✨', fandom: 'Art', category: 'Prints / Foil', price: 4000, discount: 0, deal: '' }] }));
sqlite.prepare('INSERT INTO artists VALUES (?,?,?)').run(artist.id, artist.email, artist.displayName);
sqlite.prepare('INSERT INTO artist_workspaces (artist_id,version,data) VALUES (?,?,?)').run(artist.id, 0, JSON.stringify({ ...store.emptyWorkspace, sales }));
await store.openArtistWorkspace(db, artist, '', '');
assert.equal(sqlite.prepare('SELECT count(*) AS n FROM artist_sales').get().n, 5000);
assert.equal(JSON.parse(sqlite.prepare('SELECT data FROM artist_workspaces').get().data).sales.length, 0);
await store.openArtistWorkspace(db, artist, '', '');
assert.equal(sqlite.prepare('SELECT count(*) AS n FROM artist_sales').get().n, 5000);
assert.equal((await store.readArtistWorkspace(db, artist.id, 'a')).data.sales.length, 2500);
reads = [];
writes = [];
const row = await store.readArtistWorkspace(db, artist.id, '');
const sale = { ...sales[0], id: 'new-sale' };
assert(await store.writeArtistWorkspace(db, artist.id, 0, { ...row.data, sales: [sale] }, row.data));
assert.equal(reads.length, 1);
assert.equal(writes.length, 2);
assert(!writes.some(s => s.includes('SET data')));
assert.equal(sqlite.prepare('SELECT count(*) AS n FROM artist_sales').get().n, 5001);
assert.equal(await store.writeArtistWorkspace(db, artist.id, 0, { ...row.data, sales: [{ ...sale, id: 'stale' }] }, row.data), false);
assert(!sqlite.prepare("SELECT id FROM artist_sales WHERE id='stale'").get());
// Force the insert to fail: the version gate must roll back with it.
await assert.rejects(() => store.writeArtistWorkspace(db, artist.id, 1, { ...row.data, sales: [sale] }, row.data));
assert.equal((await store.readArtistWorkspace(db, artist.id, '')).version, 1);
assert(sqlite.prepare('EXPLAIN QUERY PLAN SELECT data FROM artist_sales WHERE artist_id=? AND event_id=? ORDER BY date,id').all(artist.id, 'a').some(x => x.detail.includes('artist_sales_event_date')));
console.log('5,000-sale migration is lossless/idempotent; selected-event index, constant-size checkout writes, stale-write protection and atomic rollback passed.');
