import assert from 'node:assert/strict';
import { createTestDatabase, loadTypeScript } from './helpers/runtime.mjs';
const store = loadTypeScript('lib/artist-store.ts');
const { sqlite, db } = createTestDatabase();
const owner = { id: store.artistKey('chatgpt', 'owner'), email: 'owner@example.test', displayName: 'Owner', provider: 'chatgpt' };
const other = { id: store.artistKey('chatgpt', 'other'), email: 'other@example.test', displayName: 'Other', provider: 'chatgpt' };
const data = { categories: [], items: [], deals: [], events: [], sales: [{ id: 'legacy-sale', eventId: 'legacy-event', date: '2026-10-06' }] };
sqlite.prepare('INSERT INTO workspace VALUES (?, ?, ?)').run('main', 3, JSON.stringify(data));
let r = await store.openArtistWorkspace(db, other, owner.email);
assert.equal(r.data.sales.length, 0);
r = await store.openArtistWorkspace(db, owner, owner.email);
assert.equal(r.version, 3);
assert.equal(r.data.sales[0].id, 'legacy-sale');
assert.equal(await store.writeArtistWorkspace(db, other.id, 0, { ...store.emptyWorkspace, categories: [{ id: 'other-category' }] }), true);
assert.equal((await store.readArtistWorkspace(db, owner.id)).data.categories.length, 0);
assert.equal(await store.writeArtistWorkspace(db, other.id, 0, store.emptyWorkspace), false);
assert.equal(await store.writeArtistWorkspace(db, 'missing-artist', 3, data), false);
assert.notEqual(store.artistKey('google', 'owner'), owner.id);
const sameEmail = { ...owner, id: store.artistKey('chatgpt', 'new-subject') };
r = await store.openArtistWorkspace(db, sameEmail, owner.email);
assert.equal(r.data.sales.length, 0);
assert.equal(sqlite.prepare('SELECT data FROM workspace WHERE id = ?').get('main').data, JSON.stringify(data));
assert.throws(() => store.artistKey('google', ''), /identity/);
console.log('Account isolation, empty onboarding, owner migration, one-time claim, stale writes, provider separation, and legacy preservation passed.');
