import assert from 'node:assert/strict';
import { seed, calculate, eligible } from '../lib/model.ts';
const cart = (ids, poolId = 'p') => ids.map((itemId, n) => ({ id: String(n), itemId, poolId }));
let r = calculate(seed, cart(['design-0-foil', 'design-1-standard', 'design-2-mini']), [{ id: 'p', dealId: 'b2g1' }]);
assert.equal(r.gross, 8000);
assert.equal(r.discount, 1500);
assert.equal(r.total, 6500);
assert.equal(r.lines.length, 3);
r = calculate(seed, [...cart(['design-0-foil', 'design-1-foil', 'design-2-standard', 'design-3-mini', 'design-4-mini'], 'p'), ...cart(['design-0-standard', 'design-1-standard', 'design-2-mini'], 'q').map(u => ({ ...u, id: 'q' + u.id }))], [{ id: 'p', dealId: 'b3g2' }, { id: 'q', dealId: 'b2g1' }]);
assert.equal(r.discount, 4500);
assert.equal(r.lines.length, 8);
assert.equal(calculate(seed, cart(['design-0-mini', 'design-1-mini']), [{ id: 'p', dealId: 'b2g1' }]).discount, 0);
assert.throws(() => calculate(seed, cart(['charm-1']), [{ id: 'p', dealId: 'b2g1' }]), /eligible/);
assert.equal(eligible(seed, seed.items[0], seed.deals[0]), true);
assert.throws(() => calculate(seed, cart(['design-0-mini']), []), /pool/);
console.log('Pricing checks passed: mixed formats, stacked pools, leftovers, eligibility, and physical units.');
const pool = { id: 'foil-pool', dealId: 'b2g1' };
const assigned = cart(['design-0-foil', 'design-1-foil', 'design-2-foil'], 'foil-pool');
for (const [kind, discountValue, expected] of [['amount', 1000, 7000], ['percent', 25, 6000]]) {
  const w = { ...seed, deals: [{ id: 'discount', name: 'Discount', buy: 2, free: 0, kind, discountValue, categoryIds: ['prints'], itemIds: [] }] };
  r = calculate(w, cart(['design-0-foil', 'design-1-foil']), [{ id: 'p', dealId: 'discount' }]);
  assert.equal(r.total, expected);
  assert.equal(r.lines.length, 2);
  r = calculate(w, cart(['design-0-foil', 'design-1-foil', 'design-2-foil']), [{ id: 'p', dealId: 'discount' }]);
  assert.equal(r.total, expected + 4000);
}
const rounding = { ...seed, deals: [{ id: 'discount', name: 'Discount', buy: 2, free: 0, kind: 'amount', discountValue: 99999, categoryIds: ['prints'], itemIds: [] }] };
r = calculate(rounding, cart(['design-0-mini', 'design-1-standard']), [{ id: 'p', dealId: 'discount' }]);
assert.equal(r.total, 0);
assert(r.lines.every(l => l.discount <= l.price));
console.log('Three foil pool subtotal $80; amount/percent discounts, leftovers, caps, and pool assignment passed.');
r = calculate(seed, assigned, [pool], { kind: 'percent', value: 10 });
assert.equal(r.dealDiscount, 4000);
assert.equal(r.manualDiscount, 800);
assert.equal(r.total, 7200);
assert.equal(r.lines.reduce((sum, l) => sum + l.discount, 0), 4800);
assert.equal(r.lines.filter(l => l.discount === l.price).length, 1);
r = calculate(seed, assigned, [pool], { kind: 'amount', value: 1000 });
assert.equal(r.total, 7000);
assert.equal(r.manualDiscount, 1000);
r = calculate(seed, assigned, [pool], { kind: 'amount', value: 99999 });
assert.equal(r.total, 0);
assert(r.lines.every(l => l.discount <= l.price));
assert.throws(() => calculate(seed, assigned, [pool], { kind: 'percent', value: 101 }), /valid custom/);
assert.equal(eligible(seed, seed.items[0], { ...seed.deals[0], categoryIds: [], itemIds: [seed.items[0].id] }), false);
r = calculate(seed, cart(['design-0-mini', 'design-1-standard'], ''), [], { kind: 'amount', value: 333 });
assert.equal(r.total, 3667);
assert.equal(r.lines.reduce((sum, l) => sum + l.discount, 0), 333);
console.log('Category-only deals; after-deal custom percent/amount, caps, exact cent allocation, and free unit preservation passed.');
