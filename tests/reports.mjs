import assert from 'node:assert/strict';
import { weightedSales, eventsForYear, salesGroups, sortSalesNames, sortedSales, seed } from '../lib/model.ts';
const line = (name, price, discount = 0, category = 'Standees / Single-layer') => ({ itemId: name, name, price, discount, category, deal: '' });
assert.equal(weightedSales([line('A', 2500, 500), line('A', 2500, 500)]), 5);
assert.equal(weightedSales([line('A', 4000), line('A', 4000), line('A', 4000, 4000)]), 12);
assert.equal(weightedSales([line('A', 4000, 4000)]), 4);
const events = [{ ...seed.events[0], id: 'old', start: '2025-12-31', end: '2026-01-01' }, { ...seed.events[0], id: 'new', start: '2026-01-01' }];
assert.deepEqual(eventsForYear(events, '2026').map(e => e.id), ['new']);
assert.equal(eventsForYear(events, '').length, 2);
assert.equal(eventsForYear(events, '2024').length, 0);
const w = { ...seed, categories: [], items: [] };
const printColumns = salesGroups(seed, []).find(group => group.root === 'Prints').columns;
assert(printColumns.indexOf('Prints / Standard prints') < printColumns.indexOf('Prints / Mini prints'));
const group = salesGroups(w, [line('Zulu', 2500), line('Alpha', 2500), line('Beta', 3500), line('Zulu', 2500)])[0];
assert.deepEqual(sortSalesNames(group, 'name', 1), ['Alpha', 'Beta', 'Zulu']);
assert.deepEqual(sortSalesNames(group, 'weighted', -1), ['Zulu', 'Beta', 'Alpha']);
assert.deepEqual(sortSalesNames(group, 'units', -1), ['Zulu', 'Alpha', 'Beta']);
assert.deepEqual(sortSalesNames(group, 'Standees / Single-layer', 1), ['Alpha', 'Beta', 'Zulu']);
const sales = [{ id: 'a', date: '2026-01-01', reference: 'B', lines: [line('A', 2500)] }, { id: 'b', date: '2026-02-01', reference: 'A', lines: [line('B', 3500)] }];
assert.equal(sortedSales(sales, 'subtotal', -1)[0].id, 'b');
assert.equal(sortedSales(sales, 'reference', 1)[0].id, 'b');
console.log('Year filtering, every sales-sheet column, transaction sorting, and undiscounted weighted sales passed.');
const fandomWorkspace = { ...w, items: [{ id: 'A', name: 'A', categoryId: null, fandom: 'Current fandom' }] };
const fandomGroup = salesGroups(fandomWorkspace, [{ ...line('A', 2500), fandom: 'Recorded fandom' }])[0];
assert.equal(fandomGroup.fandoms.A, 'Recorded fandom');
const legacyGroup = salesGroups(fandomWorkspace, [line('A', 2500)])[0];
assert.equal(legacyGroup.fandoms.A, 'Current fandom');
assert.equal(weightedSales([line('A', 2500, 1000), line('A', 2500, 2500)]), 5);
console.log('Fandom snapshots and legacy fallback; $10 weighted sales baseline passed.');
